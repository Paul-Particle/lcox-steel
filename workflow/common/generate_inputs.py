#!/usr/bin/env python3
"""Write the model's input files from the input workbook: config/generated/assumptions.yaml,
config/generated/scenarios.csv and config/overlays/{scenario}.yaml for each scenario
that differs from the base.

Run: python -m common.generate_inputs [WORKBOOK] [--include-template] [--verbose]
"""
import argparse
import copy
import json
import logging
import re
from functools import reduce
from itertools import groupby
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

from common._paths import REPO_ROOT
from common._workbook_translation import RES_TECHS, WORKBOOK_SOURCES, translate_override

log = logging.getLogger(__name__)

CONFIG_DIR = REPO_ROOT / "config"
TEMPLATE_PATH = CONFIG_DIR / ".template.yaml"
TEMPLATE_SCENARIOS_PATH = CONFIG_DIR / ".template.csv"
GENERATED_DIR = CONFIG_DIR / "generated"
ASSUMPTIONS_PATH = GENERATED_DIR / "assumptions.yaml"
SCENARIOS_PATH = GENERATED_DIR / "scenarios.csv"
# Shared with the hand-kept overlays, which carry no GENERATED_NOTE and are never
# written over or removed.
OVERLAYS_DIR = CONFIG_DIR / "overlays"
DEFAULT_WORKBOOK = REPO_ROOT / "data" / "assumptions" / "Assumptions_yaml_inputs.xlsx"
INPUTS_SHEET = "assumptions_inputs"
SCENARIOS_SHEET = "scenarios_clean"
RELATIVE_CHANGE = re.compile(r"^([+-]\d+(?:\.\d+)?)%$")
SCENARIO_COLUMNS = ["scenario", "run", "route", "tech", "variant", "area", "start_date", "end_date"]
GENERATED_NOTE = "GENERATED by `python -m common.generate_inputs` from the input workbook; do not edit."
# The words the scenario tab's columns may hold (route, power supply, scenario group,
# ...) and what each means for the scenario's runs; any other word is a problem in its
# row. A run reads input series: a renewable's capacity factors at a site, or a grid's
# prices and generation mix. Each series is one line of scenarios.csv (tech, variant,
# area), and the tables say which series a run reads. For example, the row
#   import-AUS-ESP-moe-eaf-solar-grid-p95: scenario_group import, iron_location AUS,
#   steel_location ESP, route moe-eaf, power_supply res_grid, res_configuration single,
#   res_technology solar, site_variant bestsite-p95
# draws on the grid of AUS, which trades through zones, so it runs once per zone.
# Its run NSW1-ESP, route moe-eaf + -export (scenario_group import), reads three series:
#   renewables:       solar, bestsite-p95, NSW1  (because power_supply is res_grid)
#   origin_grid:      grid, emissions, NSW1      (because power_supply is res_grid)
#   destination_grid: grid, emissions, ESP       (because scenario_group is import)
ROUTES = {"h2-dri-eaf": "h2-dri-eaf", "moe-eaf": "moe-eaf", "ewin-eaf": "ew-eaf"}
# The input series every run of a scenario draws on.
SERIES_BY_POWER_SUPPLY = {"islanded_res": ["renewables"], "res_grid": ["renewables", "origin_grid"]}
SERIES_BY_SCENARIO_GROUP = {"domestic": [], "import": ["destination_grid"]}
# An import makes its iron at the origin and melts it at the destination: the
# model's `-export` twin of the route.
ROUTE_SUFFIX_BY_SCENARIO_GROUP = {"domestic": "", "import": "-export"}
RES_CONFIGURATIONS = ("single", "mix")
# A single technology's site; a mix's anchor sits at its bestsite-p95.
SITE_VARIANTS = {"bestsite-p95": "bestsite-p95", "national-average": "area-average"}
# The region each area belongs to in the workbook's regional rows, by kind of row.
AREA_REGIONS = {
    "DEU": {"wacc": "eu", "fom": "eu", "battery": "eu"},
    "ESP": {"wacc": "eu", "fom": "eu", "battery": "eu"},
    "FRA": {"wacc": "eu", "fom": "eu", "battery": "eu"},
    "AUS": {"wacc": "noneu", "fom": "aus", "battery": "global"},
    "BRA": {"wacc": "noneu", "fom": "bra", "battery": "global"},
}
# Model key -> the location whose region picks the row, the kind of row, and the row by region.
REGIONAL_SOURCES = {
    "finance.origin_wacc": ("iron_location", "wacc", "finance.other.{region}_wacc"),
    "finance.destination_wacc": ("steel_location", "wacc", "finance.other.{region}_wacc"),
    "dri-h2.opex_per_t_per_year_eur": ("iron_location", "fom", "iron.fom_eur_per_t_capacity_per_year_{region}"),
    "dri-mix.opex_per_t_per_year_eur": ("iron_location", "fom", "iron.fom_eur_per_t_capacity_per_year_{region}"),
    "dri-ng.opex_per_t_per_year_eur": ("iron_location", "fom", "iron.fom_eur_per_t_capacity_per_year_{region}"),
    "moe.opex_per_t_per_year_eur": ("iron_location", "fom", "iron.fom_eur_per_t_capacity_per_year_{region}"),
    "ew.opex_per_t_per_year_eur": ("iron_location", "fom", "iron.fom_eur_per_t_capacity_per_year_{region}"),
    "eaf.opex_per_t_per_year_eur": ("steel_location", "fom", "eaf.fom_eur_per_t_capacity_per_year_{region}"),
    "battery.capex_per_mw_eur": ("iron_location", "battery", "battery.capex_eur_per_mw_{region}"),
    "battery.capex_per_mwh_eur": ("iron_location", "battery", "battery.capex_eur_per_mwh_{region}"),
}
# Each regional key's workbook row by region, for the pick and for overrides.
REGIONAL_ROWS = {path: {regions[kind]: row.format(region=regions[kind]) for regions in AREA_REGIONS.values()}
                 for path, (_, kind, row) in REGIONAL_SOURCES.items()}
# Model key -> the workbook row an override switches it to, by sensitivity level.
# The base value comes from the translation, or from the template where the
# workbook gives none (the gas price).
SENSITIVITY_ROWS = {
    "res.wind-onshore.capex_per_mw_eur": {"low": "res.wind-onshore.capex_eur_per_mw_low",
                                          "high": "res.wind-onshore.capex_eur_per_mw_high"},
    "res.wind-onshore.opex_per_mw_per_year_eur": {"low": "res.wind-onshore.opex_eur_per_mw_per_year_low",
                                                  "high": "res.wind-onshore.opex_eur_per_mw_per_year_high"},
    "res.solar.capex_per_mw_eur": {"low": "res.solar.capex_eur_per_mw_low",
                                   "high": "res.solar.capex_eur_per_mw_high"},
    "res.solar.opex_per_mw_per_year_eur": {"low": "res.solar.opex_eur_per_mw_per_year_low",
                                           "high": "res.solar.opex_eur_per_mw_per_year_high"},
    "res.wind-offshore.capex_per_mw_eur": {"low": "res.wind-offshore.capex_eur_per_mw_low",
                                           "high": "res.wind-offshore.capex_eur_per_mw_high"},
    "res.wind-offshore.opex_per_mw_per_year_eur": {"low": "res.wind-offshore.opex_eur_per_mw_per_year_low",
                                                   "high": "res.wind-offshore.opex_eur_per_mw_per_year_high"},
    "natural_gas.price_eur_per_mwh": {"low": "natural_gas.price_eur_per_mwh_low",
                                      "high": "natural_gas.price_eur_per_mwh_high"},
}


def set_nested(tree: dict, dotted_path: str, value) -> None:
    *parents, leaf = dotted_path.split(".")
    reduce(lambda node, key: node.setdefault(key, {}), parents, tree)[leaf] = value


def flatten(tree: dict, prefix: str = "") -> dict:
    flat = {}
    for key, value in tree.items():
        flat.update(flatten(value, f"{prefix}{key}.") if isinstance(value, dict) else {f"{prefix}{key}": value})
    return flat


def read_workbook_value(workbook_inputs: pd.DataFrame, path: str, workbook_row: str) -> float:
    """A model key's value from its workbook row, in EUR."""
    if workbook_row not in workbook_inputs.index:
        raise KeyError(f"{path}: the workbook has no row {workbook_row!r}")
    value, unit = workbook_inputs.loc[workbook_row, ["value", "unit"]]
    if pd.isna(value):
        raise ValueError(f"{path}: workbook row {workbook_row!r} has no value")
    is_eur_key = "eur" in path.rsplit(".", 1)[-1].split("_")
    if "USD" in unit or is_eur_key != ("EUR" in unit):
        raise ValueError(f"{path}: workbook unit '{unit}' does not match the key's currency (the model is in EUR)")
    return float(value)


def read_overrides(cell) -> dict:
    """The row's JSON overrides, after undoing Excel's curly quotes."""
    text = "" if pd.isna(cell) else str(cell).replace("“", '"').replace("”", '"').strip()
    overrides = json.loads(text) if text else {}
    return overrides


def build_scenarios(scenario_rows: pd.DataFrame, named_inputs: dict,
                    assumptions: dict, areas: dict) -> tuple[pd.DataFrame, dict[str, dict]]:
    """The scenario table, one row per input series of a run, and each scenario's overlay.

    A scenario is one workbook row, and the tables above say what the words in its
    columns mean. It has one run, or one per market zone when it draws on the grid of
    an area that trades through zones. Its overlay holds the values of its locations'
    regions, then its overrides. `named_inputs` holds the workbook values a key can
    take by name: per sensitivity level and per region.
    """
    base_values = flatten(assumptions)
    duplicated_ids = scenario_rows["scenario_id"].duplicated(keep=False)
    row_ranges = lambda numbers: ", ".join(
        f"{run[0]}-{run[-1]}" if len(run) > 1 else str(run[0])
        for run in ([n for _, n in group] for _, group in groupby(enumerate(numbers), lambda pair: pair[1] - pair[0])))
    # Problem -> the workbook rows (as Excel numbers them) that have it.
    rows_by_problem, csv_rows, settings_by_scenario, mixes_without_partner_cells = {}, [], {}, []
    for row in scenario_rows.itertuples():
        flag = lambda problem: rows_by_problem.setdefault(problem, []).append(row.Index + 2)
        if duplicated_ids[row.Index]:
            flag(f"scenario_id {row.scenario_id!r} appears more than once")
            continue
        unknown_terms = [f"{column} {getattr(row, column)!r}" for column, terms in (
            ("route", ROUTES), ("power_supply", SERIES_BY_POWER_SUPPLY), ("scenario_group", SERIES_BY_SCENARIO_GROUP),
            ("res_configuration", RES_CONFIGURATIONS), ("iron_location", AREA_REGIONS),
            ("steel_location", AREA_REGIONS)) if getattr(row, column) not in terms]
        for term in unknown_terms:
            flag(f"unknown {term}")
        if unknown_terms:
            continue
        origin, destination = row.iron_location, row.steel_location
        is_import = row.scenario_group == "import"
        if is_import != (destination != origin):
            flag(f"scenario_group {row.scenario_group!r} with iron in {origin} and steel in {destination}")
            continue
        if is_import and not areas[destination].get("market"):
            flag(f"destination {destination!r} does not trade in a wholesale market")
            continue
        route = ROUTES[row.route] + ROUTE_SUFFIX_BY_SCENARIO_GROUP[row.scenario_group]
        dates = (str(row.start_date), str(row.end_date))

        if row.res_configuration == "single":
            if pd.notna(row.res_anchor):
                flag("res_anchor on a single technology")
                continue
            if row.site_variant not in SITE_VARIANTS:
                flag(f"unknown site_variant {row.site_variant!r} for a single technology")
                continue
            tech, variant = row.res_technology, SITE_VARIANTS[row.site_variant]
        else:
            if pd.notna(row.res_technology):
                flag("res_technology on a mix, which names its res_anchor")
                continue
            if row.site_variant != "bestsite-p95":
                flag(f"site_variant {row.site_variant!r} on a mix, whose anchor sits at its bestsite-p95")
                continue
            partner_cells = getattr(row, "res_partner_cells", np.nan)
            if pd.isna(partner_cells):
                # Skipped rather than given a number. The number might also come from the
                # config (res_cf.anchor_colocation.n_candidates): how many partner cells a
                # mix weighs is arguably a model setting and might be at home there.
                mixes_without_partner_cells.append(row.Index + 2)
                continue
            if partner_cells < 1 or partner_cells != int(partner_cells):
                flag(f"res_partner_cells {partner_cells!r} is not a positive whole number")
                continue
            # The model's anchor-colo-nN variant keeps the N best cells of each other
            # technology around the anchor's P95 site.
            tech, variant = row.res_anchor, f"anchor-colo-n{int(partner_cells)}"
        if tech not in RES_TECHS:
            flag(f"unknown renewable technology {tech!r}")
            continue

        region_by_path = {path: AREA_REGIONS[getattr(row, location)][kind]
                          for path, (location, kind, _) in REGIONAL_SOURCES.items()}
        settings = {path: named_inputs[path][region] for path, region in region_by_path.items()}
        try:
            overrides = read_overrides(row.sensitivity_overrides_JSON)
        except json.JSONDecodeError as error:
            flag(f"overrides are not JSON ({error})")
            continue
        for key, workbook_value in overrides.items():
            # A regional row reaches only the keys this scenario takes from that row.
            translated = [(path, value) for path, value
                          in translate_override(key, workbook_value, WORKBOOK_SOURCES, SENSITIVITY_ROWS, REGIONAL_ROWS)
                          if key not in REGIONAL_ROWS.get(path, {}).values()
                          or key == REGIONAL_ROWS[path][region_by_path[path]]]
            if not translated:
                flag(f"override key {key!r} is a row of a region this scenario does not take")
            for path, value in translated:
                relative = RELATIVE_CHANGE.match(value) if isinstance(value, str) else None
                if path not in base_values:
                    flag(f"override key {key!r} is not a model key")
                elif relative:
                    settings[path] = settings.get(path, base_values[path]) * (1 + float(relative.group(1)) / 100)
                elif isinstance(value, str) and value not in named_inputs.get(path, {}):
                    flag(f"{path} has no sensitivity level or region {value!r} "
                         f"(it has {sorted(named_inputs.get(path, {}))})")
                else:
                    settings[path] = named_inputs[path][value] if isinstance(value, str) else value

        # On the grid, an area without a market of its own is run once per zone it
        # trades through, and a market whose series ended before the window drops out.
        series = SERIES_BY_POWER_SUPPLY[row.power_supply] + SERIES_BY_SCENARIO_GROUP[row.scenario_group]
        registry_entry = areas[origin]
        market_until = registry_entry.get("market_until")
        if "origin_grid" not in series:
            run_areas = [origin]
        elif registry_entry.get("market"):
            run_areas = [] if market_until and dates[1] > str(market_until) else [origin]
        else:
            run_areas = sorted(registry_entry.get("zones", []))
        if not run_areas:
            flag(f"{origin} has no wholesale market covering {dates[0]}-{dates[1]}")
            continue
        # A run per zone pairs its zone's grid with its zone's renewables, never the country's.
        if row.site_variant == "national-average" and run_areas != [origin]:
            flag("national-average on the grid of an area that runs per zone")
            continue
        settings_by_scenario[row.scenario_id] = settings
        # A run is named after its origin, an import's after its destination too.
        # The origin's series first, then the destination's: the solve reads the
        # first area of a run as its origin and the second as its destination.
        for run_area in run_areas:
            run = f"{run_area}-{destination}" if is_import else run_area
            series_lines = {"renewables": (tech, variant, run_area),
                            "origin_grid": ("grid", "emissions", run_area),
                            "destination_grid": ("grid", "emissions", destination)}
            for name in series:
                csv_rows.append((row.scenario_id, run, route, *series_lines[name], *dates))

    if mixes_without_partner_cells:
        log.warning(f"skipped the mix rows that give no res_partner_cells: rows {row_ranges(mixes_without_partner_cells)}")
    problems = [f"{problem}: rows {row_ranges(numbers)}" for problem, numbers in rows_by_problem.items()]
    if problems:
        raise ValueError(f"{len(problems)} problem(s) in the scenario rows:\n  " + "\n  ".join(problems))

    scenarios = pd.DataFrame(csv_rows, columns=SCENARIO_COLUMNS)
    overlays = {scenario: {} for scenario in settings_by_scenario}
    for scenario, settings in settings_by_scenario.items():
        for path, value in settings.items():
            set_nested(overlays[scenario], path, value)
    return scenarios, overlays


def write_if_changed(path: Path, text: str) -> bool:
    changed = not path.exists() or path.read_text() != text
    if changed:
        path.write_text(text)
    return changed


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("workbook", nargs="?", type=Path, default=DEFAULT_WORKBOOK)
    parser.add_argument("--include-template", action="store_true",
                        help=f"also run the scenarios of {TEMPLATE_SCENARIOS_PATH.name}")
    parser.add_argument("--verbose", "-v", action="store_true", help="also list the workbook rows not used")
    arguments = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    log.setLevel(logging.DEBUG if arguments.verbose else logging.INFO)

    workbook_inputs = (
        pd.read_excel(arguments.workbook, sheet_name=INPUTS_SHEET)
        .rename(columns={"YAML key": "key", "Value": "value", "Unit": "unit"})
        .set_index("key")
    )
    scenario_rows = pd.read_excel(arguments.workbook, sheet_name=SCENARIOS_SHEET)
    # Temporary: the workbook writes GER for Germany, whose ISO 3166 code is DEU.
    writes_ger = scenario_rows[["iron_location", "steel_location"]].eq("GER").any(axis=1)
    if writes_ger.any():
        log.warning(f"{writes_ger.sum()} scenario rows write GER for Germany; reading it as DEU")
        scenario_rows = scenario_rows.replace({"iron_location": {"GER": "DEU"}, "steel_location": {"GER": "DEU"}})
    template = yaml.safe_load(TEMPLATE_PATH.read_text())
    areas = yaml.safe_load((CONFIG_DIR / "config.yaml").read_text())["areas"]

    workbook_values = {path: read_workbook_value(workbook_inputs, path, spec) for path, spec in WORKBOOK_SOURCES.items()}
    # Picked per scenario, by its locations or its overrides; never written into the base.
    read_named = lambda rows_by_path: {path: {name: read_workbook_value(workbook_inputs, path, row)
                                              for name, row in rows.items()}
                                       for path, rows in rows_by_path.items()}
    named_sensitivity_inputs, named_regional_inputs = read_named(SENSITIVITY_ROWS), read_named(REGIONAL_ROWS)
    named_rows = SENSITIVITY_ROWS | REGIONAL_ROWS
    rows_of_key = lambda path: [*named_rows[path].values(), *([WORKBOOK_SOURCES[path]] if path in WORKBOOK_SOURCES else [])]
    mixed_units = sorted(path for path in named_rows if workbook_inputs.loc[rows_of_key(path), "unit"].nunique() > 1)
    if mixed_units:
        raise ValueError(f"the base, sensitivity and regional rows of {mixed_units} come in different units")
    template_values = flatten(template)
    unknown_paths = sorted((set(workbook_values) | set(named_rows)) - set(template_values))
    if unknown_paths:
        raise KeyError(f"the workbook sets keys {TEMPLATE_PATH.name} does not have: {unknown_paths}")
    assumptions = copy.deepcopy(template)
    for path, value in workbook_values.items():
        set_nested(assumptions, path, value)
    scenarios, overlays = build_scenarios(scenario_rows, named_sensitivity_inputs | named_regional_inputs,
                                          assumptions, areas)
    # Template key -> how many scenarios run on its value, as neither the workbook nor their overlay sets it.
    flat_overlays = [flatten(overlay) for overlay in overlays.values()]
    backstop_counts = {path: sum(path not in overlay for overlay in flat_overlays)
                       for path in sorted(set(template_values) - set(workbook_values))}
    backstop_counts = {path: count for path, count in backstop_counts.items() if count}
    if backstop_counts:
        log.warning(f"{len(backstop_counts)} values come from {TEMPLATE_PATH.name}, as the workbook gives none; "
                    f"the scenarios (of {len(overlays)}) that run on each:\n  "
                    + "\n  ".join(f"{path}: {count}" for path, count in backstop_counts.items()))
    if arguments.include_template:
        template_scenarios = pd.read_csv(TEMPLATE_SCENARIOS_PATH, comment="#", dtype=str)
        clashing = sorted(set(template_scenarios["scenario"]) & set(overlays))
        if clashing:
            raise ValueError(f"{TEMPLATE_SCENARIOS_PATH.name} and the workbook both name scenarios {clashing}")
        scenarios = pd.concat([scenarios, template_scenarios], ignore_index=True)

    is_generated = lambda path: path.read_text().startswith(f"# {GENERATED_NOTE}")
    hand_kept = sorted(scenario for scenario in overlays
                       if (OVERLAYS_DIR / f"{scenario}.yaml").exists()
                       and not is_generated(OVERLAYS_DIR / f"{scenario}.yaml"))
    if hand_kept:
        raise ValueError(f"the overlays of {hand_kept} in {OVERLAYS_DIR} are kept by hand; "
                         f"rename the scenario or the file")

    GENERATED_DIR.mkdir(exist_ok=True)
    dump = lambda tree: yaml.safe_dump(tree, sort_keys=False, allow_unicode=True, width=1000)
    changed = [ASSUMPTIONS_PATH.name] * write_if_changed(ASSUMPTIONS_PATH, f"# {GENERATED_NOTE}\n\n" + dump(assumptions))
    changed += [SCENARIOS_PATH.name] * write_if_changed(SCENARIOS_PATH, f"# {GENERATED_NOTE}\n" + scenarios.to_csv(index=False))
    # A scenario that moves nothing gets no overlay: no file means the base as it stands.
    for scenario, overlay in overlays.items():
        overlay_path = OVERLAYS_DIR / f"{scenario}.yaml"
        if overlay:
            changed += [overlay_path.name] * write_if_changed(overlay_path, f"# {GENERATED_NOTE}\n" + dump(overlay))
    stale_overlays = [p for p in OVERLAYS_DIR.glob("*.yaml") if is_generated(p) and not overlays.get(p.stem)]
    for stale_overlay in stale_overlays:
        stale_overlay.unlink()

    used_workbook_keys = {*WORKBOOK_SOURCES.values(), *(row for rows in named_rows.values() for row in rows.values())}
    log.info(f"{len(workbook_values)} values from {arguments.workbook.name}, {len(backstop_counts)} backstop "
             f"values from {TEMPLATE_PATH.name}; {scenarios['scenario'].nunique()} scenarios, "
             f"{len(scenarios)} scenario rows, {sum(map(bool, overlays.values()))} overlays; "
             f"{len(changed)} files written, {len(stale_overlays)} stale overlays removed")
    log.debug("workbook rows not used:\n  " + "\n  ".join(sorted(set(workbook_inputs.index) - used_workbook_keys)))


if __name__ == "__main__":
    main()
